// Generates supabase/migrations/0002_seed_and_init.sql from the bundled seed recipes.
// Usage: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs'
import { INITIAL_RECIPES_DB } from '../src/lib/planner.js'

const MEAL = { 'Сніданок': 'breakfast', 'Обід': 'lunch', 'Вечеря': 'dinner' }
const q = (s) => `'${String(s).replaceAll("'", "''")}'`
const j = (s) => `${q(JSON.stringify({ uk: s }))}::jsonb`
const n = (v) => (v == null ? 'null' : v)

let sql = `-- Generated by scripts/gen-seed.mjs. Do not edit by hand.

alter table recipes alter column meal_type drop not null;
alter table recipes add column favorite boolean not null default false;
drop table favorites;
alter table shopping_extras add column amount numeric not null default 1;
alter table shopping_extras add column unit text not null default 'шт';
alter table shopping_extras add column created_at timestamptz not null default now();
alter table profiles add column seeded boolean not null default false;

-- Global seed recipes (user_id is null)
`

for (const [key, r] of Object.entries(INITIAL_RECIPES_DB)) {
  sql += `
insert into recipes (seed_key, name, description, meal_type, minutes, kcal, vegetarian, photo)
values (${q(key)}, ${j(r.name)}, ${r.description ? j(r.description) : 'null'}, ${r.mealType ? q(MEAL[r.mealType]) : 'null'}, ${n(r.minutes)}, ${n(r.kcal)}, ${!!r.vegetarian}, ${r.photo ? q(r.photo) : 'null'});
insert into recipe_ingredients (recipe_id, name, amount, unit, position)
select id, v.name, v.amount, v.unit, v.pos from recipes,
(values ${r.ingredients.map((i, p) => `(${j(i.name)}, ${i.amount}, ${q(i.unit)}, ${p})`).join(', ')}) as v(name, amount, unit, pos)
where seed_key = ${q(key)};
`
}

sql += `
-- Copies the seed recipes into the calling user's account, once.
create function init_user_data() returns void
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  already boolean;
  r record;
  new_id uuid;
begin
  if uid is null then raise exception 'not authenticated'; end if;
  insert into public.profiles (id) values (uid) on conflict do nothing;
  select seeded into already from public.profiles where id = uid for update;
  if already then return; end if;

  for r in select * from public.recipes where user_id is null loop
    insert into public.recipes (user_id, name, description, meal_type, minutes, kcal, vegetarian, photo)
    values (uid, r.name, r.description, r.meal_type, r.minutes, r.kcal, r.vegetarian, r.photo)
    returning id into new_id;
    insert into public.recipe_ingredients (recipe_id, name, amount, unit, category, position)
    select new_id, name, amount, unit, category, position
    from public.recipe_ingredients where recipe_id = r.id;
  end loop;

  update public.profiles set seeded = true where id = uid;
end $$;

revoke all on function init_user_data() from public, anon;
grant execute on function init_user_data() to authenticated;
`
writeFileSync(new URL('../supabase/migrations/0002_seed_and_init.sql', import.meta.url), sql)
console.log('recipes:', Object.keys(INITIAL_RECIPES_DB).length)
